#!/usr/bin/env node
/**
 * Builds web/js/site.js (the booking site's script) from the source files in web/src/site/.
 *
 *   node scripts/build-site.js            build once
 *   node scripts/build-site.js --watch    rebuild whenever a source file changes
 *   node scripts/build-site.js --check    exit 1 if web/js/site.js is out of date (no writes)
 *
 * The source files are joined, in manifest order, inside one shared function scope — exactly how
 * the code ran when it was a single inline script. Every top-level function is visible to every
 * file. Statements that run at load time live in 00-setup.js and must stay in their order.
 *
 * The build also stamps index.html's `site.js?v=` with a hash of the output so browsers never
 * reuse a stale copy.
 */
"use strict";

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const ROOT = path.join(__dirname, "..");
const SRC_DIR = path.join(ROOT, "web", "src", "site");
const OUT_FILE = path.join(ROOT, "web", "js", "site.js");
const INDEX_FILE = path.join(ROOT, "web", "index.html");
const MANIFEST = path.join(SRC_DIR, "manifest.json");

const BANNER =
  "/* GENERATED by scripts/build-site.js — do not edit. Edit web/src/site/ and rebuild. */\n";

function buildSource() {
  const files = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  const parts = files.map((rel) => {
    const text = fs.readFileSync(path.join(SRC_DIR, rel), "utf8").replace(/\s+$/, "");
    return "/* ── " + rel + " ── */\n" + text + "\n";
  });
  return BANNER + "(function() {\n" + parts.join("\n") + "})();\n";
}

function versionOf(source) {
  return crypto.createHash("sha1").update(source).digest("hex").slice(0, 10);
}

function stampedIndex(source) {
  const html = fs.readFileSync(INDEX_FILE, "utf8");
  const stamped = html.replace(/\/js\/site\.js\?v=[^"']*/, "/js/site.js?v=" + versionOf(source));
  if (stamped === html && html.indexOf("/js/site.js?v=" + versionOf(source)) === -1) {
    throw new Error("Could not find the site.js script tag in web/index.html");
  }
  return { html, stamped };
}

function build() {
  const source = buildSource();
  const index = stampedIndex(source);
  const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, "utf8") : "";
  const changed = current !== source || index.html !== index.stamped;
  if (current !== source) fs.writeFileSync(OUT_FILE, source);
  if (index.html !== index.stamped) fs.writeFileSync(INDEX_FILE, index.stamped);
  return { changed, version: versionOf(source), bytes: source.length };
}

function check() {
  const source = buildSource();
  const index = stampedIndex(source);
  const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, "utf8") : "";
  return current === source && index.html === index.stamped;
}

function report(result) {
  const kb = Math.round(result.bytes / 1024);
  console.log(
    (result.changed ? "Built" : "Up to date:") + " web/js/site.js (" + kb + " KB, v=" + result.version + ")"
  );
}

const mode = process.argv[2] || "";
if (mode === "--check") {
  if (check()) {
    console.log("web/js/site.js is up to date.");
  } else {
    console.error("web/js/site.js is out of date. Run: node scripts/build-site.js");
    process.exit(1);
  }
} else if (mode === "--watch") {
  report(build());
  console.log("Watching web/src/site/ …");
  let timer = null;
  fs.watch(SRC_DIR, { recursive: true }, () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      try {
        const result = build();
        if (result.changed) report(result);
      } catch (err) {
        console.error("Build failed:", err.message);
      }
    }, 80);
  });
} else {
  report(build());
}
